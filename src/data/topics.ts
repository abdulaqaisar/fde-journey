function resolveLevelId(topicId: number): number {
  const match = levelRanges.find(([, start, end]) => topicId >= start && topicId <= end)
  return match ? match[0] : 0
}

export const topics: Topic[] = topicTitles.map(([id, title]) => ({
  id,
  title,
  levelId: resolveLevelId(id),
}))

