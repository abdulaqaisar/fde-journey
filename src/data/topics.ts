/**
 * Returns topics belonging to a level.
 */
export function getTopicsByLevel(levelId: number): Topic[] {
  return topics.filter((topic) => topic.levelId === levelId)
}

/**
 * Looks up a topic by id.
 */
export function getTopicById(id: number): Topic | undefined {
  return topics.find((topic) => topic.id === id)
}

/**
 * Looks up a level by id.
 */
export function getLevelById(id: number): Level | undefined {
  return levels.find((level) => level.id === id)
}
